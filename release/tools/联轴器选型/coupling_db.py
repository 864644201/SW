def get_all_series_names():
    """返回所有系列名称"""
    return list(SERIES_MAP.keys())


def get_coupling_data(series_name):
    """返回指定系列的数据列表"""
    return SERIES_MAP.get(series_name, [])


def get_standard(series_name):
    """返回指定系列的标准号"""
    return SERIES_STANDARD.get(series_name, "")
