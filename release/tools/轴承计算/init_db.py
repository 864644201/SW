def insert_data(conn):
    """插入标准轴承数据"""
    all_bearings = DEEP_GROOVE_BALL + ANGULAR_CONTACT_BALL + TAPERED_ROLLER

    for b in all_bearings:
        conn.execute("""
            INSERT OR REPLACE INTO bearings
            (bearing_code, type, inner_dia, outer_dia, width,
             dynamic_load_C, static_load_C0, limit_speed_grease, limit_speed_oil,
             e_value, Y_value, X_value)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0.56)
        """, b)

    # 圆锥滚子轴承 X 值为 0.40
    for b in TAPERED_ROLLER:
        conn.execute(
            "UPDATE bearings SET X_value = 0.40 WHERE bearing_code = ?",
            (b[0],)
        )

    conn.commit()


def init_database():
    """初始化数据库（创建表 + 写入数据）"""
    conn = sqlite3.connect(DB_PATH)
    try:
        create_table(conn)
        insert_data(conn)
        print(f"轴承数据库初始化完成: {DB_PATH}")
        print(f"  深沟球轴承: {len(DEEP_GROOVE_BALL)} 个型号")
        print(f"  角接触球轴承: {len(ANGULAR_CONTACT_BALL)} 个型号")
        print(f"  圆锥滚子轴承: {len(TAPERED_ROLLER)} 个型号")
        print(f"  合计: {len(DEEP_GROOVE_BALL) + len(ANGULAR_CONTACT_BALL) + len(TAPERED_ROLLER)} 个型号")
    finally:
        conn.close()


if __name__ == "__main__":
    # 如果数据库已存在则先删除重建
    if os.path.exists(DB_PATH):
        os.remove(DB_PATH)
        print("已删除旧数据库")
    init_database()
