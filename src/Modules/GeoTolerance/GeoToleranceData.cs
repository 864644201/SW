        /// 天花板查找：找到主参数 >= size 的第一行索引
        /// </summary>
        public static int FindCeilingRow(double[] sizes, double size)
        {
            for (int i = 0; i < sizes.Length; i++)
            {
                if (sizes[i] >= size) return i;
            }
